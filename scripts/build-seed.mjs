// Generates supabase/seed.sql and public/data/demo-content.json from seed/seed-data.json
// Usage: npm run seed
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const data = JSON.parse(readFileSync(join(root, 'seed/seed-data.json'), 'utf8'));

// Deterministic UUIDs so re-running the seed is idempotent
const uuid = (ns, s) => {
  const h = createHash('sha1').update(`${ns}:${s}`).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
};

const q = (v) => {
  if (v === null || v === undefined || v === '') return 'null';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (Array.isArray(v)) return v.length ? `array[${v.map(q).join(', ')}]::text[]` : `'{}'::text[]`;
  return `'${String(v).replace(/'/g, "''")}'`;
};
const jq = (v) => `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;

const tables = {
  sections:        { key: 'slug', cols: ['slug', 'title', 'title_gu', 'kicker', 'intro', 'intro_gu', 'body', 'renderer', 'sort_order', 'published'] },
  daily_items:     { id: (r) => `${r.kind}${r.month_day || ''}${r.title}`, cols: ['id', 'kind', 'show_on', 'month_day', 'is_reserve', 'title', 'meaning', 'gujarati', 'hindi', 'example', 'source', 'status', 'sort_order', 'published'] },
  messages:        { id: 'heading', cols: ['id', 'heading', 'author_name', 'designation', 'body', 'signature', 'sort_order', 'published'] },
  announcements:   { id: 'title', cols: ['id', 'title', 'body', 'link_url', 'priority', 'sort_order', 'published'] },
  programs:        { id: 'code', cols: ['id', 'code', 'title', 'level_group', 'level', 'duration', 'medium', 'eligibility', 'status', 'description', 'highlights', 'future_scope', 'sort_order', 'published'] },
  program_courses: { id: (r) => `${r.program_code}${r.semester}${r.course_code}${r.title}`, cols: ['id', 'program_code', 'semester', 'course_code', 'title', 'sort_order', 'published'] },
  enrolments:      { id: (r) => `${r.program_code}${r.academic_year}${r.semester}`, cols: ['id', 'program_code', 'academic_year', 'semester', 'male', 'female', 'transgender', 'sort_order', 'published'] },
  documents:       { id: 'title', cols: ['id', 'title', 'category', 'program_code', 'academic_year', 'semester', 'course_code', 'description', 'external_url', 'sort_order', 'published'] },
  faculty:         { id: 'name', cols: ['id', 'name', 'designation', 'specialisation', 'bio', 'email', 'is_phd_guide', 'phd_completed', 'sort_order', 'published'] },
  pantheon:        { id: 'name', cols: ['id', 'name', 'tradition', 'era', 'verse', 'verse_source', 'translation', 'iks_context', 'sort_order', 'published'] },
  toppers:         { id: (r) => `${r.program_code}${r.academic_year}${r.rank}`, cols: ['id', 'program_code', 'academic_year', 'rank', 'student_name', 'percentage', 'consent', 'sort_order', 'published'] },
  links:           { id: (r) => `${r.placement}${r.label}`, cols: ['id', 'label', 'url', 'placement', 'program_code', 'kind', 'sort_order', 'published'] },
  result_notices:  { id: 'title', cols: ['id', 'title', 'exam_session', 'published_on', 'link_url', 'sort_order', 'published'] },
  gallery_items:   { id: (r) => `${r.album}${r.image_path}`, cols: ['id', 'album', 'event_date', 'title', 'caption', 'image_path', 'sort_order', 'published'] },
  alumni:          { id: 'name', cols: ['id', 'name', 'batch', 'program_code', 'present_role', 'message', 'photo_path', 'consent', 'sort_order', 'published'] },
  knowledge_chunks:{ id: 'title', cols: ['id', 'title', 'course_code', 'content', 'sort_order', 'published'] },
};

const arrayCols = new Set(['body', 'highlights', 'pathways', 'future_scope']);
const rows = {};
for (const [t, spec] of Object.entries(tables)) {
  rows[t] = (data[t] || []).map((r, i) => {
    const out = { ...r };
    if (spec.id) out.id = uuid(t, typeof spec.id === 'function' ? spec.id(r) : r[spec.id]);
    out.sort_order = r.sort_order ?? (i + 1) * 10;
    out.published = r.published ?? true;
    for (const c of spec.cols) {
      if (arrayCols.has(c)) out[c] = out[c] ?? [];
      else if (!(c in out)) out[c] = null;
      if (out[c] === '') out[c] = null;
    }
    return out;
  });
}

// ---------- seed.sql (real starter content only; demo_only rows are skipped) ----------
let sql = `-- Generated by scripts/build-seed.mjs from seed/seed-data.json — do not edit by hand.\n-- Run after all files in supabase/migrations. Safe to re-run: existing rows are updated in place.\nbegin;\n\n`;
data.settings.forEach((s, i) => {
  sql += `insert into public.site_settings (key, label, value, is_public, sort_order) values (${q(s.key)}, ${q(s.label)}, ${jq(s.value)}, ${s.is_public === false ? 'false' : 'true'}, ${(i + 1) * 10})\n  on conflict (key) do update set label = excluded.label, value = excluded.value, is_public = excluded.is_public, sort_order = excluded.sort_order;\n`;
});
sql += '\n';
for (const [t, spec] of Object.entries(tables)) {
  const pk = spec.key || 'id';
  for (const r of rows[t].filter((x) => !x.demo_only)) {
    const vals = spec.cols.map((c) => q(r[c])).join(', ');
    const upd = spec.cols.filter((c) => c !== pk).map((c) => `${c} = excluded.${c}`).join(', ');
    sql += `insert into public.${t} (${spec.cols.join(', ')}) values (${vals})\n  on conflict (${pk}) do update set ${upd};\n`;
  }
  sql += '\n';
}
sql += 'commit;\n';
writeFileSync(join(root, 'supabase/seed.sql'), sql);

// ---------- demo-content.json: the practice database (all rows, incl. hidden ones) ----------
const clean = (r) => {
  const o = { ...r };
  delete o.demo_only;
  return o;
};
const demo = {
  demo: true,
  generated_at: new Date().toISOString(),
  tables: {
    site_settings: data.settings.map((s, i) => ({ key: s.key, label: s.label, value: s.value, is_public: s.is_public !== false, sort_order: (i + 1) * 10 })),
    ...Object.fromEntries(Object.keys(tables).map((t) => [t, rows[t].map(clean)])),
  },
};
writeFileSync(join(root, 'public/data/demo-content.json'), JSON.stringify(demo));
console.log('✓ supabase/seed.sql and public/data/demo-content.json regenerated');
